const assert=require('node:assert/strict');
require('../extension/sites.js');
require('../extension/queue-core.js');
const Q=BiomazeQueueCore;
const url='https://biomaze.ir/panel/classes/c/folders/f/sections/s/video/v';
assert.equal(Q.videoURL(url+'?token=discard#class-header'),url);
for(const bad of ['http://biomaze.ir/panel/classes/c/folders/f/sections/s/video/v','https://biomaze.ir.evil.test/panel/classes/c/folders/f/sections/s/video/v','https://user:password@biomaze.ir/panel/classes/c/folders/f/sections/s/video/v','https://biomaze.ir/login','https://biomaze.ir:999/panel/classes/c/folders/f/sections/s/video/v']) assert.throws(()=>Q.videoURL(bad));
const s=Q.schedule({enabled:true,start:'23:00',end:'07:00',timeZone:'Asia/Tehran',keepAwake:true});
assert.equal(Q.inWindow(s,Date.parse('2026-10-13T20:00Z')),true);
assert.equal(Q.inWindow(s,Date.parse('2026-10-13T03:29Z')),true);
assert.equal(Q.inWindow(s,Date.parse('2026-10-13T03:30Z')),false);
assert.equal(Q.nextBoundary(s,Date.parse('2026-10-13T03:29:40Z')),Date.parse('2026-10-13T03:30Z'));
assert.throws(()=>Q.schedule({...s,start:'07:00'}));assert.throws(()=>Q.schedule({...s,end:'24:10'}));
const dst={...s,start:'01:00',end:'04:00',timeZone:'Europe/Berlin'};
assert.equal(Q.nextBoundary(dst,Date.parse('2026-10-25T00:15Z')),Date.parse('2026-10-25T03:00Z'));
const daytime={...s,start:'02:00',end:'07:00',timeZone:'UTC'};
assert.equal(Q.inWindow(daytime,Date.parse('2026-10-13T02:00Z')),true);
assert.equal(Q.inWindow(daytime,Date.parse('2026-10-13T07:00Z')),false);
assert.equal(Q.quality([{height:1080,index:1},{height:480,index:0}],720).index,0);
console.log('PASS: URL restrictions, quality fallback, start/end boundaries, midnight and DST');

const sales='https://salescenter24.com/panel/courses/topic/37744';
assert.equal(Q.videoURL(sales+'/?session=removed#x'),sales);
for(const bad of ['http://salescenter24.com/panel/courses/topic/37744','https://salescenter24.com.evil.test/panel/courses/topic/37744','https://user:password@salescenter24.com/panel/courses/topic/37744','https://salescenter24.com:444/panel/courses/topic/37744','https://salescenter24.com/login','https://salescenter24.com/panel/courses/topic/not-video','https://stream.waterse.ir/9hvpdag584oo/iframe']) assert.throws(()=>Q.videoURL(bad));
assert(BiomazeSites.playerOrigin('https://stream.waterse.ir',sales));
assert(!BiomazeSites.playerOrigin('https://stream.waterse.ir',url));
assert(!BiomazeSites.playerOrigin('https://stream.waterse.ir.evil.test',sales));
assert(BiomazeSites.controllerOrigin('https://salescenter24.com','https://stream.waterse.ir/9hvpdag584oo/iframe'));
assert(!BiomazeSites.controllerOrigin('https://evil.test','https://stream.waterse.ir/9hvpdag584oo/iframe'));
assert(!BiomazeSites.site('https://stream.waterse.ir'));
console.log('PASS: Sales Center URL normalization, origin isolation and rejection of direct player links');
